import { test, expect } from '@playwright/test';
test.beforeEach(async ({ page }) => { await page.addInitScript(() => localStorage.setItem('ln-welcome-dismissed', '1')); });
test.describe.configure({ mode: 'serial' });
const T = '2026-11-20T12:00Z';
test('globe, dashboard, timeline', async ({ page }) => {
  await page.goto(`/?site=artemis-cr&t=${T}&nointro`);
  await expect(page.getByRole('heading', { name: 'LUNAR NAVIGATOR' })).toBeVisible();
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await page.waitForTimeout(4500);
  await page.screenshot({ path: 'docs/screens/01-globe.png' });
  await expect(page.getByText('Site score', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'South pole', exact: true }).click();
  await page.waitForTimeout(3000);
  await page.screenshot({ path: 'docs/screens/02-polar.png' });
  await page.getByRole('button', { name: 'Year' }).click();
  await page.getByRole('button', { name: 'Sites', exact: true }).click();
  await page.getByRole('button', { name: /Chandrayaan-3/ }).click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: 'docs/screens/03-site.png' });
  await page.getByRole('button', { name: 'Lander view' }).click();
  await expect(page.getByText('Look at Sun')).toBeVisible();
  await page.waitForTimeout(3500);
  await page.screenshot({ path: 'docs/screens/04-lander.png' });
  await page.getByRole('button', { name: 'Look at Earth' }).click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'docs/screens/05-lander-earth.png' });
  await page.getByRole('button', { name: 'Globe' }).click();
  await page.waitForTimeout(2500);
  await page.mouse.click(760, 420);
  await page.waitForTimeout(1500);
  await expect(page.getByText('Custom site')).toBeVisible();
  expect(await page.locator('.pin-label').count()).toBeGreaterThan(0);
  expect(page.url()).toContain('lat=');
  await page.getByRole('button', { name: 'Compare' }).click();
  await page.getByRole('button', { name: 'Compare nearby sites' }).click();
  await page.waitForTimeout(1500);
  await page.getByRole('slider', { name: 'Move all dates by this many days' }).fill('7');
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'docs/screens/07-compare.png' });
  await expect(page.getByText('Highest score (ties included)').first()).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Simple', exact: true }).click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'docs/screens/08-explorer.png' });
  await page.keyboard.press('Meta+k');
  await page.getByRole('combobox', { name: 'Search sites and actions' }).fill('blue ghost');
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'docs/screens/09-palette.png' });
  await page.keyboard.press('Enter');
  await page.waitForTimeout(2500);
  await expect(page.getByText(/Blue Ghost M1/).first()).toBeVisible();
  await page.getByRole('button', { name: 'Help', exact: true }).click();
  await expect(page.getByText('Help with Lunar Navigator')).toBeVisible();
  await page.screenshot({ path: 'docs/screens/10-methodology.png' });
});
test('intro plays and hands off', async ({ page }) => {
  await page.goto(`/?site=artemis-cr&t=${T}`);
  await expect(page.getByText('Skip introduction')).toBeVisible();
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'docs/screens/00-intro.png' });
  await page.waitForTimeout(3000);
  await expect(page.getByText('Skip introduction')).toHaveCount(0);
});
