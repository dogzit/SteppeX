import type { WindowCandidate } from '@/astro/findWindow';
import { downloadFile } from './download';

const icsStamp = (ms: number) => new Date(ms).toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
const escapeIcs = (s: string) => s.replace(/[\\;,]/g, (m) => '\\' + m).replace(/\n/g, '\\n');

/** Exports the selected mission window as a single UTC VEVENT (.ics). */
export function downloadMissionIcs(siteName: string, c: WindowCandidate) {
  const desc = [
    c.earthInterval
      ? `Earth visible ${new Date(c.earthInterval.start).toISOString()} to ${new Date(c.earthInterval.end).toISOString()} (${((c.earthInterval.end - c.earthInterval.start) / 3600_000).toFixed(1)} h).`
      : 'Earth visibility not required for this window.',
    `${c.remainingIsLowerBound ? 'At least ' : ''}${(c.remainingSunlightMs / 3600_000).toFixed(1)} h of sunlight remains in this stretch after the mission ends.`,
    'Generated by Lunar Navigator. No atmosphere on the Moon: no refraction, no twilight.',
  ].join('\n');
  const uid = `${c.start}-${c.end}@lunar-navigator`;
  const body = [
    'BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//Lunar Navigator//Find a window//EN', 'CALSCALE:GREGORIAN',
    'BEGIN:VEVENT',
    `UID:${uid}`,
    `DTSTAMP:${icsStamp(Date.now())}`,
    `DTSTART:${icsStamp(c.start)}`,
    `DTEND:${icsStamp(c.end)}`,
    `SUMMARY:${escapeIcs(`Lunar mission window · ${siteName}`)}`,
    `DESCRIPTION:${escapeIcs(desc)}`,
    'END:VEVENT', 'END:VCALENDAR',
  ].join('\r\n');
  const stamp = new Date(c.start).toISOString().slice(0, 10);
  const safeName = siteName.replace(/[^a-z0-9]+/gi, '-').toLowerCase().replace(/^-+|-+$/g, '');
  downloadFile(`lunar-navigator-${safeName}-${stamp}.ics`, body, 'text/calendar');
}
