import { chromium } from '@playwright/test';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 880, height: 900 } });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('[pageerror]', e.message));
await p.goto('http://localhost:4173/?site=artemis-cr&t=2026-11-20T12:00Z&nointro');
await p.waitForTimeout(1500);
console.log('1: menu button visible?', await p.getByRole('button', { name: 'More views: Globe' }).isVisible().catch(e => e.message));
await p.getByRole('button', { name: 'More views: Globe' }).click();
console.log('2: clicked trigger');
await p.waitForTimeout(300);
console.log('3: menu items count:', await p.getByRole('menuitem').count());
console.log('4: menuitem South pole visible?', await p.getByRole('menuitem', { name: 'South pole' }).isVisible().catch(e => e.message));
await p.getByRole('menuitem', { name: 'South pole' }).click({ timeout: 5000 }).catch(e => console.log('CLICK ERR:', e.message));
console.log('5: after click, button text:', await p.getByRole('button').filter({ hasText: 'More views' }).innerText().catch(e => e.message));
await b.close();
