import { chromium } from '@playwright/test';
const T = '2026-11-20T12:00Z';
const b = await chromium.launch();
const ctx1 = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p1 = await ctx1.newPage();
await p1.goto(`http://localhost:4173/?site=artemis-cr&t=${T}&nointro`);
await p1.getByLabel('Window · days').fill('7');
await p1.waitForTimeout(500);
console.log('test4 url at end:', p1.url());
await ctx1.close();

const ctx2 = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p2 = await ctx2.newPage();
await p2.goto(`http://localhost:4173/?site=artemis-cr&t=${T}&nointro`);
const badge = p2.locator('section[aria-label="Mission viability score"] .inline-flex');
await badge.waitFor();
console.log('test5 fresh-context before:', JSON.stringify(await badge.innerText()));
console.log('test5 windowDays input:', await p2.getByLabel('Window · days').inputValue());
await ctx2.close();
await b.close();
