import { chromium } from '@playwright/test';
const T = '2026-11-20T12:00Z';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
await p.goto(`http://localhost:4173/?site=artemis-cr&t=${T}&nointro`);
const badge = p.locator('section[aria-label="Mission viability score"] .inline-flex');
await badge.waitFor();
const before = await badge.innerText();
console.log('before:', JSON.stringify(before));
const m = before.match(/sunset in (\d+)d (\d+)h (\d+)m/);
console.log('match:', m);
const [d, h, min] = [Number(m[1]), Number(m[2]), Number(m[3])];
const sunsetInMs = (d * 86400 + h * 3600 + min * 60) * 1000;
console.log('sunsetInMs', sunsetInMs, 'days', sunsetInMs/86400000);
const past = new Date(Date.parse(T) + sunsetInMs + 3600_000);
console.log('past (target fill time):', past.toISOString(), 'slice16:', past.toISOString().slice(0,16));
await p.getByLabel('Set date and time (UTC)').fill(past.toISOString().slice(0, 16));
await p.waitForTimeout(800);
console.log('mission time after:', await p.locator('header div.num.text-lg').innerText());
console.log('badge after:', await badge.innerText());
await b.close();
